/**
 * §14 — 25 items across 5 categories, 18 done, calibrated to the client's
 * own stated example: "Go-live readiness: 72%".
 */
let goLiveIdCounter = 0;
function goLiveItem(
  category: GoLiveCategory,
  label: string,
  done: boolean,
): GoLiveChecklistItem {
  goLiveIdCounter += 1;
  return { id: `GL-${goLiveIdCounter}`, category, label, done };
}

